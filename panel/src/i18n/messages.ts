export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = messages[locale][key] ?? messages.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

/** Translated message for an API / client error code, if one is known. */
export function errorMessage(locale: Locale, code: string): string | null {
  const key = `error.${code}`;
  if (key in en) {
    return translate(locale, key as MessageKey);
  }
  return null;
}
